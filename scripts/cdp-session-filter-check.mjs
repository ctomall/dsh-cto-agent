const CK = process.env.CK, BASE = 'http://127.0.0.1:8787'
const t = await (await fetch('http://127.0.0.1:9222/json/new?about:blank', { method: 'PUT' })).json()
const ws = new WebSocket(t.webSocketDebuggerUrl)
let id = 0; const pend = new Map()
const raw = (m, p = {}, ms = 15000) => Promise.race([new Promise((res, rej) => { const i = ++id; pend.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p })) }), new Promise((_, rej) => setTimeout(() => rej(new Error('超时 ' + m)), ms))])
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { const { res, rej } = pend.get(m.id); pend.delete(m.id); m.error ? rej(new Error(JSON.stringify(m.error))) : res(m.result) } })
await new Promise((r) => ws.addEventListener('open', r, { once: true }))
const ev = async (x) => (await raw('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true })).result?.value
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
await raw('Runtime.enable'); await raw('Page.enable'); await raw('Network.enable')
await raw('Network.setCookie', { name: 'cube_session', value: CK, domain: '127.0.0.1', path: '/', httpOnly: true })
await raw('Page.navigate', { url: BASE + '/' }, 25000)
await sleep(3000)
const total = await ev(`document.querySelectorAll('#sessions li').length`)
const before = await ev(`document.querySelector('#session-count')?.textContent`)
// 用「/」聚焦
await raw('Input.dispatchKeyEvent', { type: 'keyDown', key: '/', text: '/', windowsVirtualKeyCode: 191 })
await sleep(300)
const focused = await ev(`document.activeElement?.id`)
await ev(`(() => { const b = document.querySelector('#session-filter'); b.value = '验收'; b.dispatchEvent(new Event('input', { bubbles: true })); return true })()`)
await sleep(300)
const after = await ev(`({ count: document.querySelector('#session-count')?.textContent, visible: [...document.querySelectorAll('#sessions li')].filter(l => !l.hidden).length })`)
await ev(`(() => { const b = document.querySelector('#session-filter'); b.value = ''; b.dispatchEvent(new Event('input', { bubbles: true })); return true })()`)
await sleep(200)
const restored = await ev(`[...document.querySelectorAll('#sessions li')].filter(l => !l.hidden).length`)
console.log(JSON.stringify({ total, before, focused, after, restored }))
await raw('Page.close', {}, 5000).catch(() => {}); ws.close()
